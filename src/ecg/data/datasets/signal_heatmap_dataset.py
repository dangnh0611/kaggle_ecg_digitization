    def preload_sample_signal(self, sample_id):
        signal_csv_path = os.path.join(self.img_dir, str(sample_id), f"{sample_id}.csv")
        signal_df = (
            pl.scan_csv(signal_csv_path).select(pl.col("*").cast(pl.Float64)).collect()
        )
        sig_len = len(signal_df)
        signal = signal_df.to_numpy()
        null_mask = ~np.isnan(signal)
        ret = {}

        for lead_idx, lead_name in enumerate(signal_df.columns):
            assert lead_name in constants.LEAD_TO_SIG_LEN
            start_frac, end_frac = constants.LEAD_TO_SIG_LEN[lead_name]
            valid_indices = null_mask[:, lead_idx].nonzero()[0]
            first = int(valid_indices[0])
            last = int(valid_indices[-1])
            expect_start = int(start_frac * sig_len)
            expect_end = int(end_frac * sig_len - 1)
            assert first == expect_start and last == expect_end

            lead_sig = signal[first : last + 1, lead_idx]
            assert not np.isnan(lead_sig).any()
            if lead_name == "II":
                assert len(lead_sig) == sig_len
            else:
                if sig_len % 4 == 0:
                    assert len(lead_sig) == sig_len // 4
                else:
                    # int: 810, ceil: 972
                    assert len(lead_sig) == int(sig_len / 4) or len(
                        lead_sig
                    ) == math.ceil(sig_len / 4)
            ret[lead_name] = lead_sig
        return ret

    def get_cached_lead_signal(self, sample_id, lead_name):
        sample_signals = self.cached_gt_signals[sample_id]
        len10 = len(sample_signals["II"])
        len2dot5 = len(sample_signals["I"])
        assert len10 // 4 == len2dot5

        # for long signal (10 secs) with sampling rate of odd number
        # for example of fs=1025, 10250 = 2562 + 2563 + 2562 + 2563
        if lead_name == "II_short" or lead_name == "II_long_0":
            return sample_signals["II"][:len2dot5]
        elif lead_name == "II_long_1":
            return sample_signals["II"][len2dot5 : round(len10 / 2)]
        elif lead_name == "II_long_2":
            return sample_signals["II"][round(len10 / 2) : round(len10 / 2) + len2dot5]
        elif lead_name == "II_long_3":
            return sample_signals["II"][round(len10 / 2) + len2dot5 :]
        elif lead_name == "II_long_random":
            raise NotImplementedError
        else:
            return sample_signals[lead_name]

    def add_truncated_normal_noise(self, keypoints, mean=0.0, std=1.0, sigma_scale=3):
        """
        Adds noise from a truncated normal distribution to keypoints.

        Args:
            keypoints (np.ndarray): Input array of shape (N, 2).
            mean (float or array-like): The mean of the noise. Can be a scalar
                                        or an array of shape (2,) for separate X/Y means.
            std (float or array-like): The standard deviation (spread) of the noise.
                                    Can be a scalar or an array of shape (2,) for separate X/Y stds.
            sigma_scale (float): Defines the truncation bounds relative to the std.
                                min_val = mean - sigma_scale * std
                                max_val = mean + sigma_scale * std

        Returns:
            np.ndarray: Keypoints with added noise, same shape as input.
        """
        assert sigma_scale > 0

        # truncnorm bounds 'a' and 'b' are defined as standard scores (z-scores).
        # Since we want bounds at (mean +/- sigma_scale * std), the z-scores
        # are simply -sigma_scale and +sigma_scale, regardless of the actual mean/std values.

        # Scipy broadcasts 'loc' (mean) and 'scale' (std) against 'size'.
        # If mean/std are shape (2,) and size is (N, 2), it correctly applies
        # index 0 to X and index 1 to Y.
        noise = truncnorm.rvs(
            a=-sigma_scale, b=sigma_scale, loc=mean, scale=std, size=keypoints.shape
        )

        return keypoints + noise

