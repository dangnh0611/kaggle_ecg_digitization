    def _pull_item(self, idx, mix=False):
        assert not mix
        crop_name, sample_id, type_id = self.oversamples[idx]
        if type_id == "RANDOM":
            # weighted sampling a random type_id
            type_id = random.choices(
                list(self.TRAIN_RANDOM_OVERSAMPLE_WEIGHTS.keys()),
                weights=list(self.TRAIN_RANDOM_OVERSAMPLE_WEIGHTS.values()),
                k=1,
            )[0]
        else:
            assert isinstance(type_id, int)
        sample = self.stage_samples[f"{sample_id}_{type_id}"]
        assert sample_id == sample["id"] and type_id == sample["type_id"]
        sample_idx = sample["sample_idx"]
        rot_code = sample["rot_code"]
        detected_keypoints = self.detected_kpt_xys[sample_idx]
        ori_signal_gt = self.get_cached_lead_signal(sample_id, crop_name)

        # estimate relative scale to reference image of type 1 (1700x2200)
        # H is used to transform current image TO reference image
        if sample["H"] is not None:
            to_ref_H = np.array(eval(sample["H"]))
            from_ref_H = np.linalg.pinv(to_ref_H)
            # roughtly estimate the scale from current original image (000x) relative to the reference image 0001
            ori_scale_x, ori_scale_y = get_scale_xy_from_homo_mat(from_ref_H)
        else:
            # type_id == 0001
            assert type_id == 1
            ori_scale_x = ori_scale_y = 1.0

        ### LOAD RGB IMAGE
        img_path = os.path.join(
            self.img_dir, str(sample_id), f"{sample_id}-{type_id:04d}.png"
        )
        img = cv2.imread(img_path)
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
        # correct the orientation
        if rot_code is not None:
            assert rot_code == int(rot_code)
            rot_code = int(rot_code)
            img = cv2.rotate(img, rot_code)

        augmented_detected_keypoints = detected_keypoints
        if self.stage == "train":
            if random.random() < self.cfg.data.aug.grid_rand_offset_p:
                # 2. Add noise
                # scale the mean/std suitable to current image scale
                offset_mean = (
                    self.cfg.data.aug.grid_rand_offset_mean[0] * ori_scale_x,
                    self.cfg.data.aug.grid_rand_offset_mean[1] * ori_scale_y,
                )
                offset_sigma = (
                    self.cfg.data.aug.grid_rand_offset_sigma[0] * ori_scale_x,
                    self.cfg.data.aug.grid_rand_offset_sigma[1] * ori_scale_y,
                )
                augmented_detected_keypoints = self.add_truncated_normal_noise(
                    detected_keypoints,
                    mean=offset_mean,
                    std=offset_sigma,
                    sigma_scale=3,
                )

        if self.cfg.data.warp.precision == "uint8":
            assert img.dtype == np.uint8
            pass
        elif self.cfg.data.warp.precision == "float32":
            img = img.astype("float32")
        else:
            raise ValueError

